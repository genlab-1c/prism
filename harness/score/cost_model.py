# Токены BSL. Порядок важен: строка/комментарий ловятся раньше пунктуации.
# Строка 1С: "..." с удвоением кавычки ("") как экранированием; может быть многострочной.
_TOKEN_RE = re.compile(
    r"(?P<ws>\s+)"
    r"|(?P<comment>//[^\n]*)"
    r'|(?P<string>"(?:[^"]|"")*")'
    r"|(?P<ident>[A-Za-zА-Яа-яЁё_][A-Za-zА-Яа-яЁё0-9_]*)"
    r"|(?P<number>\d+\.?\d*)"
    r"|(?P<punct>[().,;+\-*/=<>%\[\]])"
    r"|(?P<other>.)"
)

# Встроенные методы со скрытой стоимостью → инструментированный аналог (см. HELPERS).
# Найти/НайтиСтроки — линейный перебор; Вставить/Удалить — сдвиг хвоста массива O(n).
# Аналоги Вставить/Удалить начисляют стоимость ТОЛЬКО массиву (по ТипЗнч): у Соответствия
# и Структуры одноимённые методы за O(1), их аналог просто делегирует без цены.
_METHOD_ANALOGS = {
    "Найти": "ПризмаНайти",
    "НайтиСтроки": "ПризмаНайтиСтроки",
    "Вставить": "ПризмаВставить",
    "Удалить": "ПризмаУдалить",
}

# Сколько аргументов у встроенной мы умеем воспроизвести. Форма вне списка НЕ подменяется:
# аналог принял бы другое число параметров и сломал бы код, который сам по себе рабочий
# (так терялась ось O у верных решений). Пустой аргумент (`Удалить(, N)`) — тоже не наша форма.
_METHOD_ARITY = {
    "Найти": (1, 2),  # Массив.Найти(Знач) · ТаблицаЗначений.Найти(Знач, "Колонки")
    "НайтиСтроки": (1,),
    "Вставить": (1, 2),  # ТаблицаЗначений.Вставить(Индекс) · Соответствие.Вставить(К, З)
    "Удалить": (1,),
}

# Длина блока хелперов в строках: на неё сдвинуты номера строк в замерочном файле
# относительно кода модели (см. harness/score/optimization_exec.py).
HELPERS_LINES = HELPERS.count("\n") + 1

# Значимые границы начала оператора (после них идёт новый оператор).
_STMT_START = {";", "Тогда", "Цикл", "Иначе", "Попытка", "Исключение"}
_TRIVIA = {"ws", "comment"}


class _Tok:
    __slots__ = ("kind", "text")

    def __init__(self, kind: str, text: str):
        self.kind, self.text = kind, text


def _tokenize(code: str) -> list[_Tok]:
    return [_Tok(m.lastgroup, m.group()) for m in _TOKEN_RE.finditer(code)]


def _receiver_start(toks: list[_Tok], sig: list[int], k: int) -> int | None:
    """Индекс в sig, с которого начинается выражение-приёмник слева от `.метод(`.

    Приёмник — это не один токен: `ИсходнаяТаблица.Колонки.Найти(Имя)` должен стать
    `ПризмаНайти(ИсходнаяТаблица.Колонки, Имя)`, а не `ПризмаНайти(Колонки, Имя)` —
    иначе имя приёмника теряется и рабочий код падает на «Symbol not found».
    Идём влево по цепочке имён, индексов и вызовов; на незнакомой форме возвращаем None,
    и тогда подмены не будет вовсе (лучше недосчитать цену, чем сломать код).
    """
    j = k - 2  # последний значимый токен приёмника (перед точкой)
    if j < 0:
        return None
    while True:
        tok = toks[sig[j]]
        if tok.kind in ("ident", "number"):
            if j - 1 >= 0 and toks[sig[j - 1]].text == "." and j - 2 >= 0:
                j -= 2  # продолжаем цепочку A.B.C влево
                continue
            return j
        if tok.text in (")", "]"):
            close = tok.text
            opener = "(" if close == ")" else "["
            depth, i = 0, j
            while i >= 0:
                text = toks[sig[i]].text
                if text == close:
                    depth += 1
                elif text == opener:
                    depth -= 1
                    if depth == 0:
                        break
                i -= 1
            if i <= 0:
                return None  # пары не нашли — форма не наша
            j = i - 1  # перед скобкой должно быть имя (вызов или индексация)
            continue
        return None


def _call_args(toks: list[_Tok], sig: list[int], open_k: int) -> list[list[str]] | None:
    """Аргументы вызова, начинающегося с `(` в позиции open_k, как список списков токенов.

    Пустой список — вызов без аргументов. None — скобки не закрыты (бить код не станем).
    """
    args: list[list[str]] = [[]]
    depth, i = 0, open_k
    while i < len(sig):
        text = toks[sig[i]].text
        if text in ("(", "["):
            depth += 1
            if not (depth == 1 and i == open_k):
                args[-1].append(text)
        elif text in (")", "]"):
            depth -= 1
            if depth == 0:
                return [] if len(args) == 1 and not args[0] else args
            args[-1].append(text)
        elif text == "," and depth == 1:
            args.append([])
        else:
            args[-1].append(text)
        i += 1
    return None


def instrument(code: str) -> str:
    """Подменяет встроенные операции со скрытой стоимостью на инструментированные аналоги.

    - `X.Найти(Y)`   → `ПризмаНайти(X, Y)`           (линейный перебор коллекции)
    - `X = X + ...;` → `X = ПризмаСклейка(X, ...);`  (склейка; аналог проверяет тип на лету,
      числам стоимость не начисляется, поэтому `Счётчик = Счётчик + 1` безопасен)

    Подмены не срабатывают внутри строк и комментариев (они — отдельные токены).
    Приёмником берётся всё выражение слева от точки; форма вызова вне _METHOD_ARITY
    остаётся как была — подмена не должна ломать работающий код.
    """
    toks = _tokenize(code)
    sig = [i for i, t in enumerate(toks) if t.kind not in _TRIVIA]  # индексы значимых токенов

    def s(k: int) -> _Tok:  # значимый токен по порядковому номеру k
        return toks[sig[k]]

    edits: list[tuple[int, int, list[_Tok]]] = []  # (real_start, real_end_excl, замена)

    k = 0
    while k < len(sig):
        t = s(k)
        # --- A.B.Найти( / X.НайтиСтроки( → Призма…(A.B, ---
        if (
            t.text in _METHOD_ANALOGS
            and k >= 2
            and s(k - 1).text == "."
            and k + 1 < len(sig)
            and s(k + 1).text == "("
        ):
            recv = _receiver_start(toks, sig, k)
            args = _call_args(toks, sig, k + 1)
            if (
                recv is not None
                and args
                and len(args) in _METHOD_ARITY[t.text]
                and all(args)  # пустой аргумент — форма не наша
                and not any(start <= sig[recv] < end for start, end, _ in edits)
            ):
                edits.append(
                    (
                        sig[recv],
                        sig[k + 1] + 1,
                        [
                            _Tok("ident", _METHOD_ANALOGS[t.text]),
                            _Tok("punct", "("),
                            *toks[sig[recv] : sig[k - 1]],  # приёмник как есть, до точки
                            _Tok("punct", ","),
                            _Tok("ws", " "),
                        ],
                    )
                )
                k += 2
                continue
        # --- начало оператора: A = A + ... ; → A = ПризмаСклейка(A, ... ); ---
        at_stmt_start = (k == 0) or (s(k - 1).text in _STMT_START)
        if (
            at_stmt_start
            and t.kind == "ident"
            and k + 3 < len(sig)
            and s(k + 1).text == "="
            and s(k + 2).text == t.text
            and s(k + 3).text == "+"
        ):
            # найти ';' этого оператора (на значимом уровне; ';' внутри строки — отдельный токен строки)
            j = k + 4
            while j < len(sig) and s(j).text != ";":
                j += 1
            if j < len(sig):
                # заменить второй `A` и `+` (sig k+2..k+3) на `ПризмаСклейка ( A ,`
                # (пробел после запятой не добавляем — уцелеет ws, что шёл после `+`)
                edits.append(
                    (
                        sig[k + 2],
                        sig[k + 3] + 1,
                        [
                            _Tok("ident", "ПризмаСклейка"),
                            _Tok("punct", "("),
                            _Tok("ident", t.text),
                            _Tok("punct", ","),
                        ],
                    )
                )
                # вставить `)` перед `;`
                edits.append((sig[j], sig[j], [_Tok("punct", ")")]))
                k = j + 1
                continue
        k += 1

    for start, end, repl in sorted(edits, key=lambda e: e[0], reverse=True):  # справа налево
        toks[start:end] = repl
    return "".join(t.text for t in toks)
